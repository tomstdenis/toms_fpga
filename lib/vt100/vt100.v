/* vt100 module

    Uses various blocks from my lib/ subdir from the toms_fpga project.  This project
is configured to include the dependencies so make sure you add that subdir as an include path.

    This emulator handles most of the vt100 escape codes on a 80x25 surface.  It supports 16 colour
foreground and background colours (r, g, b, + intensity).  It does not support "bold", nor "underlined"
attributes.  It only renders to a 80x25 text surface using 640x480 timing and RGB444 colour.  The VGA
outputs are all registered.

    The font is an IBM CP437 font with 256 symbols (supporting the drawing blocks).

    The emulator uses a 2KB BRAM for the UART which sounds excessive but the reason for that is because
it's slow.  Like really slow.  Everything happens at VGA timing which means scrolling events are slow.  For
most real use cases this should be fine but if you're blasting the UART super fast you might drop characters.

    The emulator is designed to fit on Tang Nano1K FPGAs which only support Semi-Dual Ported memories which means
that scrolling is done by chasing-the-beam as the VGA scanout reads the memory we use that output to scroll the display.
For single line scrolling this isn't too shabby but if you're scrolling multiple lines it current scrolls one line per
pass so it can be slow.  If you intend to do animations just don't scroll the screen.

*/

`timescale 1ns/1ps
`default_nettype none

module vt100
#(
    parameter VT100_FREQ=27_000_000,    // default clock for a Tang Nano 1K
    parameter VT100_BAUD=230_400,
    parameter VT100_ECHO=0,
    parameter INDEX_BITS=11,
    parameter DEF_X_DBL=0,
    parameter DEF_Y_DBL=1,
    parameter USE_COLOR=1
)
(
    input wire clk,                               // VGA clock (should be >= 25MHz)
    input wire rst_n,                             // active low reset

    input wire uart_rx,                           // uart RX pin
    output wire uart_tx,                          // uart TX pin (not currently used)

    output reg [3:0] vga_r,                       // 4-bit RGB generated by the vt100 emulator based on symbol and textout nets
    output reg [3:0] vga_g,
    output reg [3:0] vga_b,
    output reg       vga_h_pulse,                 // H sync pulse
    output reg       vga_v_pulse,                 // V sync pulse
    output reg       vga_active                   // In visible region (used by DVI TX as "data enable")
);

    // *** VID MEM ***
        // video memory (16 bit wide, 2048 deep for a 80x25 with attribute bytes)
        localparam MEM_BITS = USE_COLOR == 1 ? 16 : 8;

        reg                   mem_wr_en_a;
        reg [INDEX_BITS-1:0]  mem_addr_a;
        reg[MEM_BITS-1:0]             mem_din_a;

        reg [MEM_BITS-1:0]            mem_dout_b;
        wire [INDEX_BITS-1:0] mem_addr_b;
        reg [MEM_BITS-1:0]            vidmem[0:(1<<INDEX_BITS)-1];

        always @(posedge clk) begin
            if (mem_wr_en_a) begin
                vidmem[mem_addr_a] <= mem_din_a;
            end
            mem_dout_b <= vidmem[mem_addr_b];
        end

    // *** VGA ***
        wire [10:0] vga_x;
        wire [10:0] vga_y;
        wire        vga_h_sync;
        wire        vga_v_sync;
        wire        vga_active_f;
        
        // VGA Timing block
        vga_timing vga(
            .clk(clk),
            .rst_n(rst_n),
            .x(vga_x), .y(vga_y),
            .h_sync(vga_h_sync), .v_sync(vga_v_sync), .active_video(vga_active_f));

        // we need to figure out the font info for the /next/ cycle since this isn't combinatorial
        wire [MEM_BITS-1:0] symbol;

        // VGA text mode driver, defaults to 80x50 using an 8x8 font
        reg txt_x_dbl;
        reg txt_y_dbl;

        texy_flexy #(
            .X_FETCH_DELAY(2),
            .SYMBOL_BITS(MEM_BITS)) textdrv (
            .clk(clk), .rst_n(rst_n),
            .x(vga_x), .y(vga_y),
            .x_dbl(txt_x_dbl), .y_dbl(txt_y_dbl),
            .rd_addr(mem_addr_b), .rd_data(mem_dout_b),  .symbol(symbol));

    // *** FONT *** 
        // Font ROM
        reg [7:0]  font_dout;                           // font lookup
        reg [10:0] vga_y_p1;                            // y value we use for NEXT lookup (we factor in x being at the end of the line)
        reg [10:0] font_ad;                             // computed address based on which symbol and which y row 
        reg [7:0]  font_rom[0:2047];                    // font rom data
        reg        text_out;                            // the current pixel being drawn lensed through the current symbol through the font through vga_active                                        

        always @(posedge clk) begin
            font_dout <= font_rom[font_ad];
        end

        always @(*) begin
            // generate the address for the font lookup
            font_ad  = 0;
            vga_y_p1 = (vga_y + (vga_x == 799 ? 1'b1 : 1'b0));
            case (txt_y_dbl)
                0: font_ad  = {symbol[7:0], vga_y_p1[2:0]};
                1: font_ad  = {symbol[7:0], vga_y_p1[3:1]};
            endcase

            // generate the pixel data
            text_out = 0;
            case (txt_x_dbl)
                0: text_out = font_dout[7 - vga_x[2:0]];
                1: text_out = font_dout[7 - vga_x[3:1]];
            endcase
        end

        // font from lib/vga/blocks/
        `include "vga/blocks/fontrom.vh"

    // *** UART ***
        // uart driven by uart_tx/uart_rx pins
        reg        uart_tx_start;
        reg [7:0]  uart_tx_data_in;
        wire       uart_tx_fifo_empty;
        wire       uart_tx_fifo_full;
        reg        uart_rx_read;
        wire       uart_rx_ready;
        wire [7:0] uart_rx_byte;

        localparam 
            bauddiv   = VT100_FREQ / VT100_BAUD,
            baudwidth = $clog2(bauddiv);
        wire [baudwidth-1:0] baud_div = bauddiv;

        uart #(.FIFO_DEPTH(2048), .RX_ENABLE(1), .TX_ENABLE(VT100_ECHO), .BAUD_WIDTH(baudwidth)) mrtalky (
            .clk(clk), .rst_n(rst_n), .baud_div(baud_div),
            .uart_tx_start(uart_tx_start), .uart_tx_data_in(uart_tx_data_in),
            .uart_tx_pin(uart_tx), .uart_tx_fifo_empty(uart_tx_fifo_empty), .uart_tx_fifo_full(uart_tx_fifo_full),
            .uart_rx_pin(uart_rx), .uart_rx_read(uart_rx_read), .uart_rx_ready(uart_rx_ready), .uart_rx_byte(uart_rx_byte));

    // *** VT100 ***
    reg [INDEX_BITS-1:0]  vt100_x;
    reg [INDEX_BITS-1:0]  vt100_y;
    reg [INDEX_BITS-1:0]  vt100_sx;
    reg [INDEX_BITS-1:0]  vt100_sy;
    reg [7:0]             vt100_colour;
    reg                   vt100_linewrap;
    reg [3:0]             vt100_fsm_state;
    reg [3:0]             vt100_fsm_tag;

    reg [7:0]             vt100_term[0:3];
    reg [2:0]             vt100_terms;
    reg                   vt100_term_default;
    reg [INDEX_BITS-1:0]  vt100_i;
    reg [INDEX_BITS-1:0]  vt100_j;
    reg [7:0]             vt100_prev_char;
    reg [7:0]             vt100_curr_char;

    reg [INDEX_BITS-1:0] vt100_row_addr;
    reg [INDEX_BITS-1:0] vt100_cursor_addr;

    // these are dynamic width/height restrictions
    reg [INDEX_BITS-1:0]  vt100_width;
    reg [INDEX_BITS-1:0]  vt100_height;
    reg [INDEX_BITS-1:0]  vt100_max_dim;

    // generate current row address 
    always @(*) begin
        vt100_row_addr = 0;
        vt100_width    = 0;
        case (txt_x_dbl)
            0: begin
                vt100_row_addr = vt100_y * 80;
                vt100_width    = 80;
            end
            1: begin
                vt100_row_addr = vt100_y * 40;
                vt100_width    = 40;
            end
        endcase
        vt100_height   = 0;
        case (txt_y_dbl)
            0: vt100_height = 50;
            1: vt100_height = 25;
        endcase
        case ({txt_x_dbl, txt_y_dbl})
            2'b00: vt100_max_dim = 80 * 50;
            2'b01: vt100_max_dim = 80 * 25;
            2'b10: vt100_max_dim = 40 * 50;
            2'b11: vt100_max_dim = 40 * 25;
        endcase            
        vt100_cursor_addr = vt100_row_addr + vt100_x;
    end

    localparam
        vt100_state_idle           = 0,         // totally idle
        vt100_state_rx_char        = 1,         // receive a byte which could be to drawn or CSI/etc
        vt100_state_scroll         = 2,         // start scrolling screen up by reading from the next row
        vt100_state_scroll2        = 3,         // 2nd half of scrolling by writing to current row
        vt100_state_scroll3        = 4,         // clear the bottom row
        vt100_state_csi_terms      = 5,         // gather terms for CSIs
        vt100_state_zero_term      = 6,         // zero the currently selected term
        vt100_state_csi_term_parse = 7,         // parse current RX into a term or a command
        vt100_state_erase_cells    = 8,         // erase cells between vt100_i and vt100_j
        vt100_state_attributes     = 9,         // process the terms array for the 'm' attributes command
        vt100_state_delay          = 10,        // initiate delay waiting on uart or mem
        vt100_state_delay2         = 11;        // 2nd half of delay (also store uart rx if any

	always @(posedge clk) begin
        mem_wr_en_a     <= 1'b0;
        uart_rx_read    <= 1'b0;
        uart_tx_start   <= 1'b0;
        case (vt100_fsm_state)
            // IDLE state, handle out of bounds cursor, scroll as necessary, start processing
            // next uart input
            vt100_state_idle:
                begin
                    vt100_terms         <= 0;
                    if (vt100_y[10]) begin                          // Y went negative
                        vt100_y         <= 0;
                    end
                    if (vt100_x[10]) begin                          // X went negative
                        vt100_x         <= 0;
                    end 
                    if (vt100_x >= vt100_width) begin
                        vt100_x         <= vt100_width - 1;         // X went to the right of the viewport
                    end
                    if (vt100_y >= vt100_height) begin              // Y went to beneath the viewport, so scroll until it's in view
                        // initiate screen scroll fsm state
                        vt100_y         <= vt100_y - 1'b1;
                        vt100_i         <= 0;                       // read from scroll+80 and write to scroll 
                        vt100_fsm_state <= vt100_state_scroll;
                    end else if (uart_rx_ready) begin               // otherwise wait for a uart byte
                        uart_rx_read    <= 1;
                        vt100_fsm_tag   <= vt100_state_rx_char;
                        vt100_fsm_state <= vt100_state_delay;
                    end
                end
            // RX CHAR, handle the next uart byte
            vt100_state_rx_char:
                begin
                    vt100_prev_char <= vt100_curr_char;                  // sliding window of uart stream
                    uart_tx_start   <= VT100_ECHO;                       // echo back if enabled
                    uart_tx_data_in <= vt100_curr_char;
                    mem_addr_a      <= vt100_cursor_addr;                // address for colour/symbol pair
                    mem_din_a       <= {vt100_colour, vt100_curr_char};  // character to write to the display (this may be inhibited)
                    mem_wr_en_a     <= 1;
                    vt100_fsm_tag   <= vt100_state_idle;                 // default back to IDLE
                    vt100_fsm_state <= vt100_state_delay;
                    case (vt100_curr_char)
                        27: // ESC, turn off memory write (don't display ESC) we shifted it in to prev_char above for the next uart byte
                            begin
                                mem_wr_en_a <= 0;
                            end
                        55, 56, 91: // 7, 8, [
                            begin
                                if (vt100_prev_char == 27) begin                            // was the previous char ESC?
                                    if (uart_rx_byte == 91) begin                           // [, CSI
                                        // starting a CSI
                                        vt100_term[vt100_terms] <= 0;
                                        vt100_term_default <= 1;
                                        vt100_i            <= 0;
                                        vt100_j            <= 0;
                                        vt100_fsm_state    <= vt100_state_csi_terms;
                                        mem_wr_en_a        <= 0;
                                    end else if (uart_rx_byte == 55) begin                  // 7, save cursor
                                        vt100_sx           <= vt100_x;
                                        vt100_sy           <= vt100_y;
                                        mem_wr_en_a        <= 0;
                                    end else if (uart_rx_byte == 56) begin                  // 8, restore cursor
                                        vt100_x            <= vt100_sx;
                                        vt100_y            <= vt100_sy;
                                        mem_wr_en_a        <= 0;
                                    end                                    
                                end else begin
                                    // advance x/y because we drew a [
                                    vt100_x <= vt100_x + 1'b1;
                                    if (vt100_x == vt100_width - 1) begin
                                        if (vt100_linewrap) begin
                                            vt100_x <= 0;
                                            vt100_y <= vt100_y + 1'b1;
                                        end
                                    end
                                end
                            end
                        10: // line feed
                            begin
                                vt100_y     <= vt100_y + 1'b1;
                                vt100_x     <= 0;                                           // linux default
                                mem_wr_en_a <= 0;                                           // don't draw a line feed
                            end
                        13: // carriage return
                            begin
                                vt100_x     <= 0;
                                mem_wr_en_a <= 0;                                           // don't draw a carriage return
                            end
                        8: // bs
                            begin
                                if (vt100_x > 0) begin
                                    vt100_x     <= vt100_x - 1'b1;                          // rewind the X position and write a blank space over it
                                    mem_addr_a  <= vt100_cursor_addr - 1'b1;
                                    mem_din_a   <= {vt100_colour, 8'h20};
                                end else begin
                                    mem_wr_en_a <= 0;
                                end
                            end
                        default:                                                            // default is just draw the character in question
                            begin
                                // advance x/y
                                vt100_x <= vt100_x + 1'b1;
                                if (vt100_x == vt100_width - 1) begin
                                    if (vt100_linewrap) begin
                                        vt100_x <= 0;
                                        vt100_y <= vt100_y + 1'b1;
                                    end
                                end
                            end
                    endcase
                end
            // SCROLL, Since we use SDP memories we can't arbitrarily read the memory
            // so instead we wait for the VGA text driver to hit the address we want 
            vt100_state_scroll: // start read unless done
                begin
                    if (vt100_i == (vt100_max_dim - vt100_width)) begin
                        vt100_fsm_state <= vt100_state_scroll3;
                    end else begin
                        // wait till the VGA driver gets here
                        if (mem_addr_b == vt100_i + vt100_width) begin
                            // if addr matches on this cycle then the data is valid
                            // on the next cycle
                            vt100_fsm_state <= vt100_state_scroll2;
                        end
                    end
                end
            vt100_state_scroll2: // we hit the read address so let's write it out a line higher
                begin
                    mem_addr_a      <= vt100_i;                                         // write at current cell
                    mem_din_a       <= mem_dout_b;                                      // write what the vga text driver is reading out
                    mem_wr_en_a     <= 1;
                    vt100_i         <= vt100_i + 1'b1;                                  // advance address to next cell
                    vt100_fsm_state <= vt100_state_delay;                               // delay for the write
                    vt100_fsm_tag   <= vt100_state_scroll;                              // jump back to the scroll top
                end
            vt100_state_scroll3: // we finished scrolling the text, now we erase the last line
                begin
                    if (vt100_i == (vt100_max_dim)) begin                  // we're at the end of the screen jump back to idle
                        vt100_fsm_state <= vt100_state_idle;
                    end else begin
                        mem_addr_a      <= vt100_i;
                        mem_din_a       <= {vt100_colour, 8'h20};
                        mem_wr_en_a     <= 1'b1;
                        vt100_i         <= vt100_i + 1'b1;
                        vt100_fsm_state <= vt100_state_delay;
                        vt100_fsm_tag   <= vt100_fsm_state;
                    end
                end
            // TERM handling.  Many vt100 codes involve gathering several terms, this state zeroes the current term
            vt100_state_zero_term:
                begin
                    vt100_term[vt100_terms] <= 0;
                    vt100_fsm_state         <= vt100_state_csi_terms;
                end
            vt100_state_csi_terms:                                                      // wait for the next UART byte
                begin
                    if (uart_rx_ready) begin
                        uart_rx_read    <= 1'b1;
                        vt100_fsm_state <= vt100_state_delay;
                        vt100_fsm_tag   <= vt100_state_csi_term_parse;
                    end
                end
            vt100_state_csi_term_parse:                                                 // process the next UART byte
                begin
                    vt100_fsm_state <= vt100_state_csi_terms;
                    if (vt100_curr_char >= 48 && vt100_curr_char <= 57) begin           // 0 - 9, add it to the current term
                        vt100_term[vt100_terms] <= vt100_term[vt100_terms] * 8'd10 + vt100_curr_char - 8'd48;
                        vt100_term_default      <= 1'b0;
                    end else if (vt100_curr_char == 61 || vt100_curr_char == 63) begin  // =, ?
                        // for now just skip over this byte
                    end else if (vt100_curr_char == 59) begin                           // ;, advance to the next term, zero it, and start over
                        vt100_terms        <= vt100_terms + 1'b1;
                        vt100_fsm_state    <= vt100_state_zero_term;
                    end else begin                                                      // command character, now we consume all the terms we saved
                        vt100_fsm_state    <= vt100_state_idle;
                        case (vt100_curr_char)
                            102, 72:                                                    // f or H, move the cursor
                                begin
                                    if (vt100_term_default) begin
                                        vt100_x <= 1'b0;
                                        vt100_y <= 1'b0;
                                    end else begin
                                        vt100_y <= vt100_term[0] - 1'b1;
                                        vt100_x <= vt100_term[1] - 1'b1;
                                    end
                                end
                            65:                                                         // A (move up X lines)
                                begin
                                    vt100_y <= vt100_y - vt100_term[0];
                                end
                            66:                                                         // B (move down X lines)
                                begin
                                    vt100_y <= vt100_y + vt100_term[0];
                                end
                            67:                                                         // C (move left X columns)
                                begin
                                    vt100_x <= vt100_x - vt100_term[0];
                                end
                            68:                                                         // D (move right X columns)
                                begin
                                    vt100_x <= vt100_x + vt100_term[0];
                                end
                            69:                                                         // E (reset x, move down X lines)
                                begin
                                    vt100_x <= 0;
                                    vt100_y <= vt100_y + vt100_term[0];
                                end
                            70:                                                         // F (reset x, move up X lines)
                                begin
                                    vt100_x <= 0;
                                    vt100_y <= vt100_y - vt100_term[0];
                                end
                            71:                                                         // G (move to column X)
                                begin
                                    vt100_x <= vt100_term[0] - 1'b1;
                                end
                            74:                                                         // J (erase)
                                begin
                                    if (vt100_term[0] == 0 || vt100_term_default) begin // cursor to end of screen
                                        vt100_fsm_state <= vt100_state_erase_cells;
                                        vt100_i         <= vt100_cursor_addr;
                                        vt100_j         <= vt100_max_dim;
                                    end else if (vt100_term[0] == 1) begin              // from cursor to start of screen
                                        vt100_fsm_state <= vt100_state_erase_cells;
                                        vt100_j         <= vt100_cursor_addr;
                                        vt100_i         <= 0;
                                    end else if (vt100_term[0] == 2) begin              // entire screen
                                        vt100_fsm_state <= vt100_state_erase_cells;
                                        vt100_i         <= 0;
                                        vt100_j         <= vt100_max_dim;
                                    end
                                end
                            75:                                                         // K (erase row)
                                begin
                                    if (vt100_term[0] == 0 || vt100_term_default) begin // cursor to end of line
                                        vt100_fsm_state <= vt100_state_erase_cells;
                                        vt100_i         <= vt100_cursor_addr;
                                        vt100_j         <= vt100_row_addr + vt100_width - vt100_x;
                                    end else if (vt100_term[0] == 1) begin              // from start of line to cursor
                                        vt100_fsm_state <= vt100_state_erase_cells;
                                        vt100_i         <= vt100_row_addr;
                                        vt100_j         <= vt100_cursor_addr;
                                    end else if (vt100_term[0] == 2) begin              // erase current line
                                        vt100_fsm_state <= vt100_state_erase_cells;
                                        vt100_i         <= vt100_row_addr;
                                        vt100_j         <= vt100_row_addr + vt100_width;
                                    end
                                end
                            104:                                                        // h (set mode bit)
                                begin
                                    case (vt100_term[0])
                                        7:  vt100_linewrap <= 1'b1;                    // linewrap
                                        250:  txt_x_dbl    <= 1'b1;                    // enable X double
                                        251:  txt_y_dbl    <= 1'b1;                    // enable Y double
                                    endcase
                                end
                            108:                                                        // l (clear mode bit)
                                begin
                                    case (vt100_term[0])
                                        7:  vt100_linewrap <= 1'b0;                    // linewrap
                                        250:  txt_x_dbl    <= 1'b0;                    // disable X double
                                        251:  txt_y_dbl    <= 1'b0;                    // disable Y double
                                    endcase
                                end
                            109:                                                        // m (attributes)
                                begin
                                    vt100_fsm_state     <= vt100_state_attributes;
                                    // why swap?  we use vt100_terms as an index into the DFF array 
                                    // so here we save the # of terms in j and then reset terms to zero
                                    // this saves LUT4s and timing
                                    vt100_j             <= vt100_terms;                 // save the # of terms
                                    vt100_terms         <= 0;                           // step through them starting at 0
                                end
                            115:                                                        // s (save cursor position)
                                begin
                                    vt100_sx            <= vt100_x;
                                    vt100_sy            <= vt100_y;
                                end
                            117:                                                        // u (restore cursor)
                                begin
                                    vt100_x             <= vt100_sx;
                                    vt100_y             <= vt100_sy;
                                end
                        endcase
                    end
                end
            // erase cells between vt100_i and vt100_j - 1 inclusive
            vt100_state_erase_cells:
                begin
                    vt100_fsm_state     <= vt100_state_idle;
                    if (vt100_i != vt100_j) begin
                        vt100_i         <= vt100_i + 1'b1;
                        mem_wr_en_a     <= 1'b1;
                        mem_din_a       <= {vt100_colour, 8'h20};
                        mem_addr_a      <= vt100_i;
                        vt100_fsm_state <= vt100_state_delay;
                        vt100_fsm_tag   <= vt100_fsm_state;
                    end
                end
            vt100_state_attributes:
                begin
                    // handle attribute vt100_term[vt100_i]
                    vt100_terms <= vt100_terms + 1'b1;
                    if (vt100_term[vt100_terms] == 0) begin                                             // reset attributes
                        vt100_colour      <= {1'b0, 1'b0, 3'b0, 3'b111};
                    end else if (vt100_term[vt100_terms] == 1) begin                                    // set bold
                        vt100_colour[7:6] <= 2'b11;
                    end else if (vt100_term[vt100_terms] == 2) begin                                    // set dim
                        vt100_colour[7:6] <= 2'b00;
                    end else if (vt100_term[vt100_terms] >= 30 && vt100_term[vt100_terms] <= 37) begin  // foreground
                        vt100_colour[2:0] <= vt100_term[vt100_terms][2:0] - 3'd30;
                    end else if (vt100_term[vt100_terms] >= 40 && vt100_term[vt100_terms] <= 47) begin  // background
                        vt100_colour[5:3] <= vt100_term[vt100_terms][2:0] - 3'd40;
                    end else if (vt100_term[vt100_terms] == 39) begin                                   // default foreground
                        vt100_colour[2:0] <= 3'd7;
                        vt100_colour[7]   <= 1'b0;
                    end else if (vt100_term[vt100_terms] == 49) begin                                   // default background
                        vt100_colour[5:3] <= 3'd0;
                        vt100_colour[6]   <= 1'b0;
                    end else if (vt100_term[vt100_terms] >= 90 && vt100_term[vt100_terms] <= 97) begin  // bright foreground
                        vt100_colour[7]   <= 1;
                        vt100_colour[2:0] <= vt100_term[vt100_terms][2:0] - 3'd90;
                    end else if (vt100_term[vt100_terms] >= 100 && vt100_term[vt100_terms] <= 107) begin // bright background
                        vt100_colour[6]   <= 1;
                        vt100_colour[5:3] <= vt100_term[vt100_terms][2:0] - 3'd100;
                    end
                    if (vt100_j == vt100_terms) begin
                        vt100_fsm_state <= vt100_state_idle;
                    end
                end
            vt100_state_delay:
                begin
                    vt100_fsm_state <= vt100_state_delay2;
                end
            vt100_state_delay2:
                begin
                    vt100_curr_char <= uart_rx_byte;
                    vt100_fsm_state <= vt100_fsm_tag;
                end
        endcase

		if (~rst_n) begin
            mem_wr_en_a      <= 0;
            vt100_x          <= 0;
            vt100_y          <= 0;
            vt100_sx         <= 0;
            vt100_sy         <= 0;
            vt100_colour     <= {1'b0, 1'b0, 3'b0, 3'b111};
            vt100_linewrap   <= 1'b0;
            vt100_fsm_state  <= vt100_state_idle; 
            vt100_i          <= 0;
            vt100_j          <= 0;
            vt100_prev_char  <= 0;
            uart_rx_read     <= 0;
            uart_tx_start    <= 0;
            txt_x_dbl        <= DEF_X_DBL;
            txt_y_dbl        <= DEF_Y_DBL;
		end
	end

    // grab the current symbol attribute and latch it so it's valid for the entire width of the font
    reg [1:0] text_at;
    reg [2:0] text_fg;
    reg [2:0] text_bg;
    reg [3:0] rgbon;

	always @(*) begin
        // default to blank (needed when in blanking regions)
		vga_r   = 0;
		vga_g   = 0;
		vga_b   = 0;
		
        // render the foreground/background colour using the VT100 palette, with support
        // bold/dim attributes
		if (vga_active) begin
            if (USE_COLOR == 1) begin
                // extract attribute information
                text_at = symbol[15:14];
                text_bg = symbol[13:11];
                text_fg = symbol[10:8];
                rgbon   = {text_at[text_out], 3'b111};

                case (text_out ? text_fg : text_bg)
                    0: // black
                        {vga_r, vga_g, vga_b} = 12'b0000_0000_0000;
                    1: // red
                        {vga_r, vga_g, vga_b} = {rgbon, 4'b0000, 4'b0000};
                    2: // green
                        {vga_r, vga_g, vga_b} = {4'b0000, rgbon, 4'b0000};
                    3: // yellow
                        {vga_r, vga_g, vga_b} = {rgbon, rgbon, 4'b0000};
                    4: // blue
                        {vga_r, vga_g, vga_b} = {4'b0000, 4'b0000, rgbon};
                    5: // magenta
                        {vga_r, vga_g, vga_b} = {rgbon, 4'b0000, rgbon};
                    6: // cyan
                        {vga_r, vga_g, vga_b} = {4'b0000, rgbon, rgbon};
                    7: // white
                        {vga_r, vga_g, vga_b} = {rgbon, rgbon, rgbon};
                endcase
            end else begin
                    vga_r = text_out ? 4'b1111: 4'b0000;
                    vga_g = vga_r;
                    vga_b = vga_r;
            end
		end

        // drive the VGA signals out
        vga_h_pulse = vga_h_sync;
        vga_v_pulse = vga_v_sync;
        vga_active  = vga_active_f;
	end
endmodule

